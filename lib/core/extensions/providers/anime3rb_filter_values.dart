final List<String> anime3rbYearValues = List<String>.generate(
  2026 - 1969,
  (index) => '${2026 - index}',
  growable: false,
);

/// Converts a studio label to its Anime3rb creator slug when not explicitly mapped.
String anime3rbStudioSlug(String label) {
  final trimmed = label.trim();
  final known = anime3rbStudioValues[trimmed];
  if (known != null) return known;
  for (final entry in anime3rbStudioValues.entries) {
    if (entry.key.toLowerCase() == trimmed.toLowerCase()) {
      return entry.value;
    }
  }
  return trimmed
      .toLowerCase()
      .replaceAll('°', '')
      .replaceAll("'", '')
      .replaceAll('.', '')
      .replaceAll(RegExp(r'[^a-z0-9]+'), '-')
      .replaceAll(RegExp(r'^-+|-+$'), '');
}
